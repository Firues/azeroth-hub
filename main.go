// Command wow-hub is a control panel for the local AzerothCore WoTLK
// repack.
//
// It replaces three console windows with one, and - the reason it exists -
// it stops the stack in the right order: world, then auth, then database.
// worldserver writes to the database as it shuts down, so a MySQL that
// leaves first leaves it writing into a dead connection.
//
// Nothing here holds logic. Logic that lived in main could not be tested
// without a Wails runtime, so there is none: this file assembles
// collaborators and hands them to app.App.
package main

import (
	"context"
	"database/sql"
	"embed"
	"io/fs"
	"os"
	"time"

	"github.com/wailsapp/wails/v3/pkg/application"
	"github.com/wailsapp/wails/v3/pkg/events"

	"wow-hub/internal/dbping"
	"wow-hub/internal/health"
	"wow-hub/internal/i18n"
	"wow-hub/internal/logx"
	"wow-hub/internal/osops"
	"wow-hub/internal/repack"
	"wow-hub/internal/supervisor"
)

//go:embed all:frontend/dist
var embedded embed.FS

// The panel's icon: the dark plate and the gold A from app.css, drawn in
// build/appicon.png and compiled into build/windows/icon.ico.
//
// The .ico, not the .png. Wails hands these bytes to CreateIconFromResourceEx,
// which wants icon data it can read as a bitmap - it takes a PNG straight
// through and the call fails, and the window silently ends up with no icon.
//
//go:embed build/windows/icon.ico
var appIcon []byte

// statusInterval is the status loop's period. Refresh emits only on a real
// change, and health folds in every fifth tick, so a one-second loop is
// cheap.
const statusInterval = time.Second

func main() {
	// Locate the repack from our own path.
	//
	// A failure here is NOT fatal, and that is deliberate. The build runs this
	// binary once to generate the JS bindings, from a temporary directory that
	// has no repack above it - exiting would fail the build. More importantly, a
	// user who moved the app wants to SEE "repack not found" in a window, not a
	// console flash and nothing else. So the app opens anyway and the Health
	// screen reports it in terms they can act on.
	lay, err := repack.Locate()
	if err != nil {
		lay = repack.Layout{}
		println("wow-hub: репак не найден —", err.Error())
	}

	// The logger needs a real directory, and there is not one until the
	// repack is found.
	var logger *logx.Logger
	if lay.Root != "" {
		l, lerr := logx.New(lay.LogsDir)
		if lerr != nil {
			// Also not fatal. Losing the log is bad; refusing to start
			// because of it is worse.
			println("wow-hub: лог недоступен:", lerr.Error())
		} else {
			logger = l
			defer logger.Close()
			logger.Info("wow-hub запущен", "root", lay.Root)
		}
	}

	ops := osops.New()

	// The ping needs the password out of temp\mysql_ac.conf. If that file is
	// missing, say so and carry on: every other feature still works, and the
	// Health screen reports the problem in terms the user can act on.
	var pinger dbping.Pinger
	if lay.MySQLPassConf != "" {
		p, perr := dbping.NewFromFile(lay.MySQLPassConf)
		if perr != nil {
			if logger != nil {
				logger.Error("пинг БД недоступен", "err", perr)
			}
			println("wow-hub: проверка БД недоступна —", perr.Error())
		} else {
			pinger = p
			defer pinger.Close()
		}
	}

	// The realm queries need the same password and a pool of their own.
	//
	// Separate on purpose: the pinger runs on a five-second loop and is what
	// decides whether the database counts as alive, so a slow aggregate query
	// must not share its single connection. Both are read-only, so two pools
	// cannot disagree about any data.
	var realm *sql.DB
	if lay.MySQLPassConf != "" {
		r, rerr := dbping.Open(lay.MySQLPassConf)
		if rerr != nil {
			if logger != nil {
				logger.Error("чтение базы недоступно", "err", rerr)
			}
			println("wow-hub: чтение базы недоступно —", rerr.Error())
		} else {
			realm = r
			defer realm.Close()
		}
	}

	// fs.Sub is not optional. Without it every asset resolves under
	// /frontend/... and the window comes up blank. The path inside the
	// embed.FS is frontend/dist, because that is the folder Vite writes.
	sub, err := fs.Sub(embedded, "frontend/dist")
	if err != nil {
		fatal(logger, i18n.T("fatal.frontend"), err)
	}

	app := application.New(application.Options{
		Name: "Azeroth Hub",
		// The window icon is set from here, not from the icon embedded in the
		// executable. Wails tries resource id 3 first and falls back to this,
		// and the fallback is what fires: the .syso is generated by winres,
		// and it numbers its icons its own way. Explorer, the taskbar and
		// Alt+Tab get the icon from the .syso and do not go through this at
		// all - the two are not redundant, they cover different places.
		Icon: appIcon,
		Assets: application.AssetOptions{
			Handler: application.AssetFileServerFS(sub),
		},
		Windows: application.WindowsOptions{
			// Close the window without quitting: this is the whole premise.
			DisableQuitOnLastWindowClosed: true,
		},
	})

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	sink := newEventSink(app)

	// The cycle: the supervisor needs an App to ask before force-killing, and
	// the App needs a supervisor to do anything. Build the App first, hand it
	// the supervisor afterwards.
	panel := NewApp(Deps{
		Health: health.NewRunner(ops, lay, pinger),
		Sink:   sink,
		Ops:    ops,
		Layout: lay,
		DB:     realm,
		Clock:  osops.RealClock{},
		Logger: logger,
	})
	sup := supervisor.New(ops, osops.RealClock{}, lay, sink, pinger, confirmer{panel}, supervisor.Conf{})
	sup.SetLogger(logger)
	panel.setSupervisor(sup)

	// Registered after the panel exists rather than in Options.Services,
	// because the panel's dependencies reach back into this application -
	// the event sink needs it to emit at a window. Options.Services cannot
	// express that; RegisterService can.
	app.RegisterService(application.NewService(newService(panel)))

	go statusLoop(ctx, panel)

	// newWindow builds the panel's window and hands it to the sink.
	//
	// A window, not a hide. The webview is what costs ~285 MB across twelve
	// WebView2 processes, and only closing the window kills it. That is also
	// why this is a function and not a variable: the tray calls it again to
	// bring the panel back, because a closed window cannot be revived -
	// WebviewWindow.Show goes through Run, which returns early on a non-nil
	// impl that closing never clears.
	// buildWindow makes a window. It does NOT record it in the sink:
	// showPanel does that under its own lock, and a builder that also recorded
	// it would reopen the gap that lets two clicks build two windows.
	buildWindow := func() *application.WebviewWindow {
		w := app.Window.NewWithOptions(application.WebviewWindowOptions{
			Title:     "Azeroth Hub",
			Width:     1280,
			Height:    830,
			URL:       "/",
			Frameless: true,
			// No system frame, so nothing hides the first paint and the white
			// default would flash before the page's dark background lands. Same
			// value as --background in app.css; change both together.
			BackgroundColour: application.NewRGB(7, 10, 15),
		})
		// A window has to say goodbye on its way out, or the sink keeps
		// pointing at a dead one and the tray icon goes dead with it.
		w.RegisterHook(events.Common.WindowClosing, func(*application.WindowEvent) {
			sink.forget(w)
		})
		return w
	}

	// Bringing an existing window forward.
	showWindow := func(w *application.WebviewWindow) {
		w.Show()
		w.Focus()
	}

	// The panel opens on launch, and by the same path the tray brings it back.
	sink.showPanel(buildWindow, showWindow)

	// The tray is how the panel comes back. Closing the window does not quit
	// the app (DisableQuitOnLastWindowClosed), so without this there would be
	// no way to reopen the panel short of double-clicking the exe again -
	// which is exactly the thing that made the panel feel broken when it
	// simply went away.
	tray := app.SystemTray.New()
	tray.SetLabel("Azeroth Hub")
	// Set explicitly rather than letting the tray fall back to the icon in the
	// executable. The fallback works only while the .syso happens to be in
	// place, and a tray icon is the one thing a person looks for when the
	// panel is not on screen.
	tray.SetIcon(appIcon)

	// The left click, not just the menu item. Wails only gives a left click a
	// handler of its own when the tray is attached to a window, and ours is
	// not: the window is rebuilt each time, so there is no single one to attach
	// to. Without this line the icon is decorative - the panel comes back from
	// the menu and from nowhere else.
	tray.OnClick(func() { sink.showPanel(buildWindow, showWindow) })

	trayMenu := app.Menu.New()
	trayMenu.Add(i18n.T("tray.open")).OnClick(func(_ *application.Context) {
		sink.showPanel(buildWindow, showWindow)
	})
	trayMenu.AddSeparator()
	trayMenu.Add(i18n.T("tray.quit")).OnClick(func(_ *application.Context) {
		app.Quit()
	})
	tray.SetMenu(trayMenu)

	// Stop polling and stop emitting. The server is deliberately left
	// running: closing the panel is not a request to stop it, and the next
	// launch re-adopts whatever it finds.
	app.OnShutdown(func() {
		cancel()
		sink.clear()
	})

	if err := app.Run(); err != nil {
		fatal(logger, i18n.T("fatal.window"), err)
	}
}

// statusLoop is the one goroutine that keeps the UI current.
func statusLoop(ctx context.Context, app *App) {
	ticker := time.NewTicker(statusInterval)
	defer ticker.Stop()

	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
			app.tick(ctx)
		}
	}
}

// fatal reports a failure that leaves no window to report it in, and exits.
//
// println alone is not enough. The app is linked as a GUI binary and has no
// console, so a startup failure would close before the user saw anything at
// all - the one case where the Health screen, which reports everything else, is
// unavailable by definition. The message box is the only channel left.
func fatal(logger *logx.Logger, what string, err error) {
	if logger != nil {
		logger.Error(what, "err", err)
	}
	println("wow-hub:", what, "-", err.Error())
	messageBox(i18n.T("fatal.title"), what+":\n"+err.Error())
	os.Exit(1)
}
