func TestLoadMySQLPasswordNeverLeaksThePasswordInErrors(t *testing.T) {
	// The password lands in logs\wow-hub.log and in screenshots. An error
	// that echoes the file's contents would publish it. This file really
	// does fail to load - the only password in it belongs to another
	// section - so the error is on the path a user will actually hit.
	conf := "[mysqldump]\npassword = \"hunter2\"\n"
	_, err := LoadMySQLPassword(writeConf(t, conf))
	if err == nil {
		t.Fatal("expected an error: the only password is in the wrong section")
	}
	if strings.Contains(err.Error(), "hunter2") {
		t.Fatalf("error message leaks the password: %q", err)
	}
	if !strings.Contains(err.Error(), "mysql_ac.conf") {
		t.Fatalf("error = %q, want it to name the file instead of quoting it", err)
	}
}

func TestLoadMySQLPasswordToleratesUnclosedSectionHeader(t *testing.T) {
	// "[oops" with no closing bracket is not worth rejecting: by then the
	// [client] password has already been read, and failing here would turn
	// a harmless trailing line into "wrong password".
	got, err := LoadMySQLPassword(writeConf(t, "[client]\npassword = \"acore\"\n\n[oops\n"))
	if err != nil {
		t.Fatalf("LoadMySQLPassword: %v, want the already-parsed password returned", err)
	}
	if got != "acore" {
		t.Fatalf("got %q, want %q", got, "acore")
	}
}

// --- the maintenance account used to shut MySQL down ---

func TestMySQLRootCredentialsFallBackToTheDocumentedDefaults(t *testing.T) {
	// The repack ships root/test and no config file for it. A missing file
	// must not stop MySQL from being shut down cleanly - that path is the
	// one that protects the characters database.
	path := filepath.Join(t.TempDir(), "temp", "mysql_root.conf")

	user, pass := MySQLRootCredentials(path)
	if user != DefaultMySQLRootUser || pass != DefaultMySQLRootPass {
		t.Fatalf("got %q/%q, want the documented defaults", user, pass)
	}
}

func TestMySQLRootCredentialsReadAnOverrideFile(t *testing.T) {
	// A user who changed the root password can keep the clean shutdown
	// working by writing temp\mysql_root.conf.
	p := writeConf(t, "[client]\nuser = admin\npassword = \"s3cret\"\n")

	user, pass := MySQLRootCredentials(p)
	if user != "admin" || pass != "s3cret" {
		t.Fatalf("got %q/%q, want admin/s3cret", user, pass)
	}
}

func TestMySQLRootCredentialsFillTheMissingHalfFromDefaults(t *testing.T) {
	// A file that names only a password still beats no file at all.
	p := writeConf(t, "[client]\npassword = \"s3cret\"\n")

	user, pass := MySQLRootCredentials(p)
	if user != DefaultMySQLRootUser {
		t.Fatalf("user = %q, want the default %q", user, DefaultMySQLRootUser)
	}
	if pass != "s3cret" {
		t.Fatalf("password = %q, want the override", pass)
	}
}

func TestMySQLRootCredentialsIgnoreOtherSections(t *testing.T) {
	p := writeConf(t, "[mysqldump]\nuser = nobody\npassword = \"hunter2\"\n")

	user, pass := MySQLRootCredentials(p)
	if user != DefaultMySQLRootUser || pass != DefaultMySQLRootPass {
		t.Fatalf("got %q/%q, want the defaults - a [mysqldump] credential is not the maintenance account", user, pass)
	}
}
